import createClient from "openapi-fetch";

import { toApiError } from "./errors";
import type { paths } from "./schema";

/** Browser path of the API: Next.js rewrites /api/* to FastAPI, so cookies stay same-origin. */
export const API_BASE = "/api";
/** Any non-empty value; FastAPI refuses state-changing requests without it (CSRF defence). */
export const CSRF_HEADER = "X-Requested-With";
export const CSRF_VALUE = "fetch";

type Fetch = (request: Request) => Promise<Response>;

/**
 * A fetch that sends cookies and the CSRF header, and on a 401 refreshes the session once and
 * retries. Concurrent 401s share one refresh call (the refresh token rotates, so a second
 * parallel refresh would look like token re-use and revoke every session).
 */
export function sessionFetch(base: Fetch = (request) => fetch(request)): Fetch {
  let refreshing: Promise<boolean> | null = null;

  const refresh = () => {
    refreshing ??= base(
      new Request(`${location.origin}${API_BASE}/auth/refresh`, {
        method: "POST",
        credentials: "include",
        headers: { [CSRF_HEADER]: CSRF_VALUE },
      }),
    )
      .then((response) => response.ok)
      .catch(() => false)
      .finally(() => {
        refreshing = null;
      });
    return refreshing;
  };

  return async (input) => {
    const request = new Request(input, { credentials: "include" });
    if (request.method !== "GET") request.headers.set(CSRF_HEADER, CSRF_VALUE);
    const retry = request.clone();
    const response = await base(request);
    const isAuthCall = new URL(request.url).pathname.startsWith(`${API_BASE}/auth/`);
    if (response.status !== 401 || isAuthCall) return response;
    return (await refresh()) ? base(retry) : response;
  };
}

/** A typed client for the FastAPI schema (generated by `pnpm gen:api`). */
export function createApi(fetchImpl: Fetch = sessionFetch()) {
  return createClient<paths>({
    baseUrl: typeof location === "undefined" ? API_BASE : `${location.origin}${API_BASE}`,
    fetch: fetchImpl,
  });
}

export const api = createApi();

/** The data of an openapi-fetch result, or throw an ApiError (with the request id). */
export function unwrap<T>(result: { data?: T; error?: unknown; response: Response }): T {
  if (result.response.ok) return result.data as T;
  throw toApiError(result.response, result.error);
}
