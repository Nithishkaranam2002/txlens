"""The model card: what the model is for, what it was trained on, how well it did, its limits.

Rendered by `make risk-train` from the same development run that is registered, so the card,
the MLflow run and the registry version always describe the same model.
"""

from datetime import date

import pandas as pd

from txlens_backend.risk import LABEL_TEXT
from txlens_backend.risk.develop import CHAMPION_MARGIN, EXTERNAL_CENTER, Development, labelled
from txlens_backend.risk.evaluate import MIN_EVENTS, Summary, TestScores
from txlens_backend.risk.features import FEATURES
from txlens_backend.risk.models import Kind
from txlens_backend.risk.registry import INTENDED_USE, MODEL_NAME

NAMES = {Kind.LOGISTIC: "Logistic regression", Kind.LIGHTGBM: "Gradient boosting (LightGBM)"}
BY = {"age_band": "Age band", "sex": "Sex"}


def pct(value: float) -> str:
    return f"{100 * value:.1f}%"


def data_rows(frame: pd.DataFrame, label: str) -> list[str]:
    data = labelled(frame, label)
    rows = []
    for tenant, part in data.groupby("tenant", sort=True):
        role = "external test" if tenant == EXTERNAL_CENTER else "development + internal test"
        rows.append(f"| {tenant} | {role} | {part['key'].nunique()} | {len(part)} | "
                    f"{int(part[label].sum())} | {pct(float(part[label].mean()))} |")  # fmt: skip
    return rows


def score_row(name: str, s: TestScores) -> str:
    return (f"| {name} | {s.n_visits} ({s.n_events} events) | {s.auroc.text()} | "
            f"{s.auprc.text()} (prevalence {s.prevalence:.3f}) | {s.brier.text(4)} | "
            f"{s.calibration_intercept:.2f} / {s.calibration_slope:.2f} |")  # fmt: skip


def fairness_rows(summary: Summary) -> list[str]:
    rows = []
    for r in summary.fairness:
        if r["auroc"] is None:
            scored = f"not scored (<{MIN_EVENTS} events)"
            rows.append(f"| {BY[r['by']]} | {r['group']} | {r['n_visits']} | {scored} | | "
                        f"{pct(r['alert_rate'])} | |")  # fmt: skip
            continue
        rows.append(f"| {BY[r['by']]} | {r['group']} | {r['n_visits']} | {r['n_events']} | "
                    f"{r['auroc']:.3f} | {pct(r['alert_rate'])} | "
                    f"{pct(r['sensitivity'])} |")  # fmt: skip
    return rows


def render(
    development: Development, summary: Summary, frame: pd.DataFrame, version: str,
    extract_date: date,
) -> str:  # fmt: skip
    """The model card as Markdown."""
    kind = development.champion
    other = Kind.LIGHTGBM if kind is Kind.LOGISTIC else Kind.LOGISTIC
    bi, be = summary.burden_internal, summary.burden_external
    lines = [
        f"# Model card: {MODEL_NAME} v{version}",
        "",
        f"**{LABEL_TEXT}**",
        "",
        f"Generated by `make risk-train` from data extracted {extract_date.isoformat()}. "
        "Full evaluation: `evals/reports/risk_model.md` (`make risk-report`).",
        "",
        "## Intended use",
        f"- {INTENDED_USE}",
        "- Users: transplant clinicians and data stewards reviewing the surveillance worklist. "
        "Researchers never see individual scores.",
        "- The score is a prompt to look at the patient, next to the rule-engine flags. It never "
        "replaces a biopsy, and no action is taken automatically.",
        "",
        "## Out of scope",
        "- Real patients: the model has only ever seen synthetic data.",
        "- For-cause (unscheduled) dd-cfDNA draws, pediatric recipients, organs other than kidney "
        "and heart.",
        "- Diagnosing rejection or choosing a treatment.",
        "",
        "## Model",
        f"- Champion: **{NAMES[kind]}** with {dict(development.best[kind])}. Rule fixed before "
        f"testing: gradient boosting wins only if its cross-validated AUPRC beats logistic "
        f"regression by at least {CHAMPION_MARGIN}.",
        "- Prediction: at a scheduled surveillance visit, once its results are back. Outcome: a "
        "biopsy showing TCMR, ABMR or mixed rejection in the next 90 days (borderline counts "
        "as no rejection).",
        "- Production version: the champion refit on all three centers. Its performance is "
        "estimated by the internal and external tests below, which it did not take part in.",
        "",
        "## Features (all known on or before the visit day)",
        "| Feature | Unit | Meaning |",
        "|---|---|---|",
        *[f"| {f.label} | {f.unit} | {f.description} |" for f in FEATURES],
        "",
        "## Data (synthetic)",
        "| Center | Role | Patients | Labelled visits | Rejection visits | Prevalence |",
        "|---|---|---|---|---|---|",
        *data_rows(frame, development.label),
        "",
        "Internal test: 20% of center A+B patients (no patient in both development and test). "
        "External test: center C, never used for training or model choice.",
        "",
        "## Performance (95% intervals resample patients)",
        "| Model / test | Visits | AUROC | AUPRC | Brier | Calibration intercept / slope |",
        "|---|---|---|---|---|---|",
        score_row(f"{NAMES[kind]}, internal", summary.internal[kind]),
        score_row(f"{NAMES[kind]}, external (center C)", summary.external[kind]),
        score_row(f"{NAMES[other]}, internal", summary.internal[other]),
        score_row(f"{NAMES[other]}, external (center C)", summary.external[other]),
        "",
        "## Compared with the rule engine at the same alert burden",
        "The model alerts on the highest-scored share of visits equal to the share the rule "
        "engine (any medium/high flag) alerts on.",
        "",
        "| Test | Alert rate | Rejections caught: rules | Model | Difference (model - rules) |",
        "|---|---|---|---|---|",
        f"| Internal | {pct(bi.alert_rate)} | {bi.rule_sensitivity.text()} | "
        f"{bi.model_sensitivity.text()} | {bi.difference.text()} |",
        f"| External | {pct(be.alert_rate)} | {be.rule_sensitivity.text()} | "
        f"{be.model_sensitivity.text()} | {be.difference.text()} |",
        "",
        "## Fairness checks (internal + external test visits)",
        f"Groups with fewer than {MIN_EVENTS} rejection visits are not scored.",
        "",
        "| By | Group | Visits | Rejection visits | AUROC | Alert rate | Rejections caught |",
        "|---|---|---|---|---|---|---|",
        *fairness_rows(summary),
        "",
        "## Limits",
        "- Synthetic data: the generator raises dd-cfDNA and creatinine 14-56 days before a "
        "rejection biopsy and makes DSA appear before ABMR. Tacrolimus variability, donor type, "
        "delayed graft function and age have no built-in effect, so the model cannot learn one. "
        "Real-world performance is unknown.",
        "- Labels come from OMOP: pathology reports still in the review queue are missing and "
        "clinic-note mentions fill part of the gap. The evaluation compares them with the "
        "generator's truth.",
        "- The draw reason never reaches OMOP: a visit is the first dd-cfDNA draw in a schedule "
        "window, so some for-cause draws are included (measured in the evaluation).",
        "- Heart recipients are few; their results have wide intervals.",
        "",
        "## Monitoring",
        "- Every prediction stores the model name and version, its inputs and top contributions.",
        "- Each nightly run stores the population stability index (PSI) of the scores against "
        "the training reference; the evaluation report adds feature PSI. PSI above 0.25 means "
        "the inputs have shifted and the model should be re-validated before further use.",
        "",
    ]
    return "\n".join(lines)
